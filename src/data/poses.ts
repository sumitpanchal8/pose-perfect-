// Helper functions for accessing poses by gender
export function getPosesByGender(gender: 'male' | 'female'): Pose[] {
  return (gender === 'male' ? MALE_POSES : FEMALE_POSES).map(p => ({
    ...p,
    title: p.title || p.name,
    description: p.description || (p.instructions && p.instructions[0]) || p.bodyPosition,
    distance: p.distance || p.cameraDistance || 'Medium distance',
    phoneOrientation: p.phoneOrientation || (p.framing?.toLowerCase().includes('vertical') ? 'Vertical' : 'Vertical (portrait)'),
    shoulderPosition: p.shoulderPosition || 'Drop shoulders gently down and back to lengthen the neck.',
    legPosition: p.legPosition || 'Shift 75% of body weight to back foot for natural silhouette.',
    mistakes: p.mistakes || [
      'Standing completely rigid like a statue with tense neck muscles',
      'Facing camera dead-on with zero angle or depth',
      'Holding hands limp and lifeless at sides',
    ],
    confidenceTip: p.confidenceTip || 'Inhale slowly, exhale through gently parted lips, and think of something that made you laugh today.',
  }));
}

export const ALL_POSES: Pose[] = [...getPosesByGender('male'), ...getPosesByGender('female')];

export function getAllPoses(): Pose[] {
  return ALL_POSES;
}

export function getPoseById(id: string): Pose | undefined {
  return ALL_POSES.find(p => p.id === id);
}

// Get Pose of the Day based on today's date and active gender
export function getPoseOfTheDay(gender: 'male' | 'female'): Pose {
  const poses = getPosesByGender(gender);
  const now = new Date();
  const dayOfYear = Math.floor((now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / 1000 / 60 / 60 / 24);
  const index = Math.abs(dayOfYear) % poses.length;
  return poses[index];
}

export interface FilterPosesOptions {
  category?: string;
  location?: string;
  mood?: string;
  difficulty?: string;
  searchQuery?: string;
}

export function filterPoses(poses: Pose[], options: FilterPosesOptions): Pose[] {
  const { category, location, mood, difficulty, searchQuery } = options;

  return poses.filter((pose) => {
    if (category && category !== 'all' && pose.category !== category) {
      return false;
    }

    if (location && location !== 'all') {
      const match = pose.location.some((loc) =>
        loc.toLowerCase().includes(location.toLowerCase()) ||
        location.toLowerCase().includes(loc.toLowerCase())
      );
      if (!match) return false;
    }

    if (mood && mood !== 'all') {
      const match = pose.mood.some((m) =>
        m.toLowerCase().includes(mood.toLowerCase()) ||
        mood.toLowerCase().includes(m.toLowerCase())
      );
      if (!match) return false;
    }

    if (difficulty && difficulty !== 'all' && pose.difficulty !== difficulty) {
      return false;
    }

    if (searchQuery && searchQuery.trim() !== '') {
      const q = searchQuery.toLowerCase().trim();
      const nameMatch = (pose.name || pose.title || '').toLowerCase().includes(q);
      const descMatch = (pose.description || (pose.instructions || []).join(' ')).toLowerCase().includes(q);
      const bodyMatch = (pose.bodyPosition || '').toLowerCase().includes(q);
      const handMatch = (pose.handPosition || '').toLowerCase().includes(q);
      const tagsMatch = (pose.tags || []).some((t) => t.toLowerCase().includes(q));
      const subMatch = (pose.subCategory || '').toLowerCase().includes(q);

      if (!nameMatch && !descMatch && !bodyMatch && !handMatch && !tagsMatch && !subMatch) {
        return false;
      }
    }

    return true;
  });
}
